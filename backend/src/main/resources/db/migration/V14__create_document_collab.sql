-- Collaborative editing (Yjs/CRDT). The server stores the binary Yjs data it relays and never interprets it:
-- a log of updates plus an occasional full-state snapshot uploaded by a client (which lets old updates be dropped).
-- documents.content stays the plain-text copy used for search, lists, export and versions.
CREATE TABLE document_collab (
    document_id  UUID                     PRIMARY KEY REFERENCES documents (id) ON DELETE CASCADE,
    -- Bumped when the text is replaced from outside (restore, plain save): clients holding an older epoch must reload.
    epoch        INTEGER                  NOT NULL,
    snapshot     BYTEA,
    -- Every update with seq <= snapshot_seq is contained in the snapshot.
    snapshot_seq BIGINT                   NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE document_updates (
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id UUID                     NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
    epoch       INTEGER                  NOT NULL,
    data        BYTEA                    NOT NULL,
    author_id   UUID,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_document_updates ON document_updates (document_id, epoch, seq);
